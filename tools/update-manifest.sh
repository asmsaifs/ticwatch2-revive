#!/usr/bin/env bash
# Maintainer helper: refresh the checksums in manifest.tsv from the APKs under apks/<target>/.
#  - rows already in the manifest keep their package/name; only the md5 is refreshed
#  - a new APK is added automatically if aapt2 is available (package + label are read from it),
#    otherwise add its row by hand: target<TAB>package<TAB>file<TAB>md5<TAB>name
#  - rows whose APK no longer exists are dropped
#  - X-arm64.apk next to X.apk: target becomes phone64 / phone32 (see tools/make-arm64-variant.sh)
set -eu
cd "$(dirname "${BASH_SOURCE[0]}")/.."

md5_of() { if command -v md5sum >/dev/null 2>&1; then md5sum "$1" | awk '{print $1}'; else md5 -q "$1"; fi; }

find_aapt2() {
  if command -v aapt2 >/dev/null 2>&1; then command -v aapt2; return; fi
  local d
  for d in "${ANDROID_HOME:-}" "${ANDROID_SDK_ROOT:-}" "$HOME/Library/Android/sdk" "$HOME/Android/Sdk"; do
    [ -n "$d" ] && [ -d "$d/build-tools" ] || continue
    ls -d "$d"/build-tools/*/aapt2 2>/dev/null | sort -V | tail -1 && return
  done
}
AAPT2=$(find_aapt2 || true)

tmp=$(mktemp)
{
  printf '# target\tpackage\tfile\tmd5\tname\n'
  printf '# Generated by tools/update-manifest.sh (CI also does it on every push that touches apks/). Tab separated.\n'
  printf '# target = watch | phone (phone32 / phone64 = only for phones that can / cannot run 32-bit ARM code). The installers compare md5 with the APK installed on the device and only (re)install on a difference.\n'
} > "$tmp"

for apk in apks/watch/*.apk apks/phone/*.apk; do
  [ -f "$apk" ] || continue
  target=$(basename "$(dirname "$apk")")
  # X-arm64.apk = build for 64-bit-only devices; its X.apk sibling then only goes to 32-bit-capable ones
  case "$apk" in
    *-arm64.apk) target=${target}64 ;;
    *) [ -f "${apk%.apk}-arm64.apk" ] && target=${target}32 ;;
  esac
  sum=$(md5_of "$apk")
  row=$(awk -F'\t' -v f="$apk" '$3==f {print; exit}' manifest.tsv 2>/dev/null || true)
  # a new -arm64 variant inherits package + name from its full build
  [ -z "$row" ] && case "$apk" in *-arm64.apk) row=$(awk -F'\t' -v f="${apk%-arm64.apk}.apk" '$3==f {print; exit}' manifest.tsv 2>/dev/null || true) ;; esac
  if [ -n "$row" ]; then
    pkg=$(printf '%s' "$row" | cut -f2); name=$(printf '%s' "$row" | cut -f5)
  elif [ -n "$AAPT2" ]; then
    badge=$("$AAPT2" dump badging "$apk" 2>/dev/null)
    pkg=$(printf '%s\n' "$badge" | sed -n "s/^package: name='\([^']*\)'.*/\1/p" | head -1)
    name=$(printf '%s\n' "$badge" | sed -n "s/^application-label:'\(.*\)'$/\1/p" | head -1)
    [ -n "$pkg" ] || { echo "cannot read package name of $apk" >&2; exit 1; }
    [ -n "$name" ] || name=$pkg
    echo "added new app: $name ($pkg)" >&2
  else
    echo "$apk is not in manifest.tsv and aapt2 is not available: add its row by hand" >&2; exit 1
  fi
  printf '%s\t%s\t%s\t%s\t%s\n' "$target" "$pkg" "$apk" "$sum" "$name" >> "$tmp"
done

if cmp -s "$tmp" manifest.tsv; then echo "manifest.tsv already up to date"; rm -f "$tmp"
else mv "$tmp" manifest.tsv; echo "manifest.tsv updated:"; grep -v '^#' manifest.tsv; fi
